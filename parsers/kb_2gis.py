def fetch_region(region_name: str, max_retries: int = 3):
    """Один запрос: возвращает {(org_id, region_id_2gis): branch_count}."""
    params = {
        "q": f"Красное & Белое, {region_name}",
        "key": API_KEY,
        "page_size": PAGE_SIZE,
        "fields": "items.org,items.region_id",
    }
    for attempt in range(1, max_retries + 1):
        try:
            resp = requests.get(BASE_URL, params=params, timeout=20)
            data = resp.json()
        except (requests.RequestException, ValueError) as e:
            print(f"  ! сеть: {e}")
            time.sleep(attempt * 4)
            continue

        code = data.get("meta", {}).get("code")
        if code == 200:
            orgs = {}
            for it in data.get("result", {}).get("items", []):
                org = it.get("org") or {}
                if not org.get("id") or not org.get("branch_count"):
                    continue
                if not NAME_PATTERN.search(org.get("primary") or org.get("name") or ""):
                    continue
                orgs[(org["id"], it.get("region_id"))] = org["branch_count"]
            return orgs
        if code == 404:  # ничего не найдено — честный ноль
            return {}

        print(f"  ! попытка {attempt}/{max_retries}, код {code}")
        time.sleep(attempt * 4)
    return None


def main():
    results = {}
    seen = {}  # (org_id, region_id_2gis) -> регион, где впервые засчитали
    total = 0

    for i, region in enumerate(REGIONS, 1):
        orgs = fetch_region(region)
        if orgs is None:
            print(f"[{i}/{len(REGIONS)}] {region}: ОШИБКА")
            results[region] = {"count": None}
            time.sleep(1)
            continue

        count = sum(orgs.values())
        new = sum(v for k, v in orgs.items() if k not in seen)
        dup_of = sorted({seen[k] for k in orgs if k in seen})
        for k in orgs:
            seen.setdefault(k, region)
        total += new

        flag = f"  (та же зона 2GIS, что и {', '.join(dup_of)})" if dup_of else ""
        print(f"[{i}/{len(REGIONS)}] {region}: {count}{flag}")
        results[region] = {"count": count, "new": new, "dup_of": dup_of}

        with open("kb_by_region_2gis.json", "w", encoding="utf-8") as f:
            json.dump(results, f, ensure_ascii=False, indent=2)
        time.sleep(1)

    print(f"\nИТОГО (без двойного счёта агломераций): {total}")
    print("Сохранено в kb_by_region_2gis.json")


